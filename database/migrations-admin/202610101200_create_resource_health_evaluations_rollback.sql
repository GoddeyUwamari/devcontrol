-- Rollback: remove resource health evaluation storage
-- Paired with: 202610101200_create_resource_health_evaluations.sql
--
-- Manual only. database/migrate.js never runs a file whose name contains
-- "rollback" (getMigrationFiles()), so --execute-only cannot target this
-- file, and CI's schema bootstrap skips it too. Run it as the postgres role,
-- the same identity as the admin track, in ONE transaction and stopping at
-- the first error:
--
--   psql -v ON_ERROR_STOP=1 --single-transaction -d <database> \
--     -f 202610101200_create_resource_health_evaluations_rollback.sql
--
-- Precondition: no deployed release reads or writes these tables. The
-- stored health evaluations are discarded; they are regenerated by the next
-- evaluation run once the tables exist again.
--
-- Removes only what the paired migration created, and refuses (instead of
-- cascading) when anything else depends on it:
--   - resource_health_evaluation_results and resource_health_evaluation_runs;
--   - aws_resources_id_org_unique, only if no foreign key other than
--     resource_health_evaluation_results_resource_fk references it;
--   - the paired migration's own schema_migrations row, and no other.
-- No statement uses CASCADE: an unexpected dependent (a view, another
-- table's foreign key) makes the DROP fail, and the transaction rolls back.

SET LOCAL lock_timeout = '5s';

DO $$
DECLARE
  dependents TEXT;
BEGIN
  IF to_regclass('resource_health_evaluation_runs') IS NULL
     OR to_regclass('resource_health_evaluation_results') IS NULL THEN
    RAISE EXCEPTION
      'resource_health_evaluation_runs/results not found -- the paired migration is not applied '
      'here; nothing to roll back. Refusing to proceed.';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'aws_resources_id_org_unique' AND conrelid = 'aws_resources'::regclass AND contype = 'u'
  ) THEN
    RAISE EXCEPTION 'aws_resources_id_org_unique not found -- refusing to proceed. Investigate before re-running.';
  END IF;

  -- Foreign keys that use aws_resources_id_org_unique's index, other than the
  -- one this migration created.
  SELECT string_agg(format('%s on %s', fk.conname, fk.conrelid::regclass), ', ')
    INTO dependents
    FROM pg_constraint fk
    JOIN pg_constraint uq
      ON uq.conname = 'aws_resources_id_org_unique' AND uq.conrelid = 'aws_resources'::regclass
   WHERE fk.contype = 'f'
     AND fk.conindid = uq.conindid
     AND NOT (fk.conname = 'resource_health_evaluation_results_resource_fk'
              AND fk.conrelid = 'resource_health_evaluation_results'::regclass);
  IF dependents IS NOT NULL THEN
    RAISE EXCEPTION
      'aws_resources_id_org_unique is referenced by other foreign keys (%) -- refusing to drop it. '
      'Remove or migrate those first.', dependents;
  END IF;

  -- Foreign keys from any other table into the two tables being dropped.
  SELECT string_agg(format('%s on %s', fk.conname, fk.conrelid::regclass), ', ')
    INTO dependents
    FROM pg_constraint fk
   WHERE fk.contype = 'f'
     AND fk.confrelid IN ('resource_health_evaluation_runs'::regclass, 'resource_health_evaluation_results'::regclass)
     AND fk.conrelid NOT IN ('resource_health_evaluation_runs'::regclass, 'resource_health_evaluation_results'::regclass);
  IF dependents IS NOT NULL THEN
    RAISE EXCEPTION
      'resource_health_evaluation_* is referenced by other foreign keys (%) -- refusing to drop it.', dependents;
  END IF;
END $$;

-- Results first: its foreign key depends on aws_resources_id_org_unique.
DROP TABLE resource_health_evaluation_results;
DROP TABLE resource_health_evaluation_runs;
ALTER TABLE aws_resources DROP CONSTRAINT aws_resources_id_org_unique;

-- The paired migration's own ledger row only, so it can be applied again.
DELETE FROM schema_migrations
 WHERE migration_name = '202610101200_create_resource_health_evaluations.sql';
